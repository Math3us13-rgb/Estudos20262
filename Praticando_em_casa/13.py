#Estrutura de decisão questão 13:

num_semana = int(input('Digite um número de 1 a 7:'))
if num_semana == 1:
    print('1-Domingo')
elif num_semana == 2:
    print('2-Segunda-feira.')
elif num_semana == 3:
    print('3-Terça-feira.')
elif num_semana == 4:
    print('4-Quarta-feira.')
elif num_semana == 5:
    print('5-Quinta-feira.')
elif num_semana == 6:
    print('6-Sexta-feira.')
elif num_semana == 7:
    print('7-Sábado.')
else:
    print('Número inválido.')